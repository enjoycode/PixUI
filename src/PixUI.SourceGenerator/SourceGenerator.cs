using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Xml.XPath;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace PixUI;

[Generator]
public class SourceGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Add the marker attribute to the compilation.
        context.RegisterPostInitializationOutput(ctx =>
        {
            ctx.AddSource($"{nameof(SourceGenAttributes.StylePropertyAttribute)}.g.cs",
                SourceText.From(SourceGenAttributes.StylePropertyAttribute, Encoding.UTF8));
            ctx.AddSource($"{nameof(SourceGenAttributes.StyleObjectAttribute)}.g.cs",
                SourceText.From(SourceGenAttributes.StyleObjectAttribute, Encoding.UTF8));
            ctx.AddSource($"{nameof(SourceGenAttributes.StylableWidgetAttribute)}.g.cs",
                SourceText.From(SourceGenAttributes.StylableWidgetAttribute, Encoding.UTF8));
            ctx.AddSource($"{nameof(SourceGenAttributes.BindableWidgetAttribute)}.g.cs",
                SourceText.From(SourceGenAttributes.BindableWidgetAttribute, Encoding.UTF8));
            ctx.AddSource($"{nameof(SourceGenAttributes.BindablePropertyAttribute)}.g.cs",
                SourceText.From(SourceGenAttributes.BindablePropertyAttribute, Encoding.UTF8));
        });

        // Filter classes annotated with attribute. Only filtered Syntax Nodes can trigger code generation.
        var provider = context.SyntaxProvider
            .CreateSyntaxProvider(
                (s, _) => s is ClassDeclarationSyntax,
                (ctx, _) => TypeHelper.GetClassDeclarationForSourceGen(ctx))
            .Where(t => t.GenType != SourceGenClassType.None)
            .Select((t, _) => t);

        // Generate the source code.
        context.RegisterSourceOutput(context.CompilationProvider.Combine(provider.Collect()),
            ((ctx, t) => GenerateCode(ctx, t.Left, t.Right)));
    }

    /// <summary>
    /// Generate code action.
    /// It will be executed on specific nodes (ClassDeclarationSyntax annotated with the [Report] attribute) changed by the user.
    /// </summary>
    /// <param name="context">Source generation context used to add source files.</param>
    /// <param name="compilation">Compilation used to provide access to the Semantic Model.</param>
    /// <param name="classDeclarations">Nodes annotated with the [Report] attribute that trigger the generate action.</param>
    private static void GenerateCode(SourceProductionContext context, Compilation compilation,
        ImmutableArray<SourceGenClassInfo> classDeclarations)
    {
        // Go through all filtered class declarations.
        foreach (var item in classDeclarations)
        {
            // We need to get semantic model of the class to retrieve metadata.
            var semanticModel = compilation.GetSemanticModel(item.ClassDeclaration.SyntaxTree);

            // Symbols allow us to get the compile-time information.
            if (semanticModel.GetDeclaredSymbol(item.ClassDeclaration) is not INamedTypeSymbol classSymbol)
                continue;

            var namespaceName = classSymbol.ContainingNamespace.ToDisplayString();

            // 'Identifier' means the token of the node. Get class name from the syntax node.
            var className = item.ClassDeclaration.Identifier.Text;

            if (item.GenType == SourceGenClassType.StyleObject)
            {
                var sb = new StringBuilder();
                GenerateStyleObject(sb, namespaceName, className, item.ClassDeclaration, semanticModel);
                // Add the source code to the compilation.
                context.AddSource($"{className}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
            }
            else if (item.GenType.HasFlag(SourceGenClassType.StylableWidget) ||
                     item.GenType.HasFlag(SourceGenClassType.BindableWidget))
            {
                var sb = new StringBuilder();
                GenerateWidgetObject(sb, item, namespaceName, className, semanticModel);
                context.AddSource($"{className}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
            }
        }
    }

    private static void GenerateWidgetObject(StringBuilder sb, in SourceGenClassInfo classInfo,
        string namespaceName, string className, SemanticModel semanticModel)
    {
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("using System;");
        sb.AppendLine("using PixUI;");
        sb.AppendLine();

        sb.AppendLine($"namespace {namespaceName};");
        sb.AppendLine($"partial class {className}");
        sb.AppendLine("{");

        if (classInfo.GenType.HasFlag(SourceGenClassType.StylableWidget))
            sb.Append(GenerateWidgetStyleProperty(namespaceName, className, classInfo.StyleType!));

        if (classInfo.GenType.HasFlag(SourceGenClassType.BindableWidget))
        {
            var bindableProperties = 
                TypeHelper.GetBindableProperties(classInfo.ClassDeclaration, semanticModel).ToArray();
            foreach (var propInfo in bindableProperties)
            {
                var returnType = propInfo.PropertySymbol.Type.ToDisplayString();
                var propertyName = propInfo.PropertySymbol.Name;
                var fieldName = "field";

                sb.Append($"\t{propInfo.Modifiers}");
                if (!string.IsNullOrEmpty(propInfo.Modifiers)) sb.Append(' ');
                sb.AppendLine($"partial {returnType} {propertyName}");
                sb.AppendLine("\t{");
                //getter
                sb.AppendLine("\t\tget;");

                //setter
                sb.AppendLine("\t\tset");
                sb.AppendLine("\t\t{");
                if (!string.IsNullOrEmpty(propInfo.Validator))
                {
                    sb.Append($"\t\t\tif(!(");
                    sb.AppendFormat(propInfo.Validator!, "value.Value");
                    sb.AppendLine("))");
                    sb.AppendLine(
                        $"\t\t\t\tthrow new PropertyValueInvalidException(nameof({className}), nameof({propertyName}), \"{propInfo.Validator}\");");
                }

                sb.AppendLine($"\t\t\tvar changed = {fieldName}.Value != value.Value;");
                sb.AppendLine($"\t\t\t{fieldName}.State?.RemoveListener({propInfo.Listener});");
                sb.AppendLine($"\t\t\t{fieldName} = value;");
                sb.AppendLine($"\t\t\t{fieldName}.State?.AddListener({propInfo.Listener});");

                sb.AppendLine($"\t\t\tif (changed) {propInfo.Listener}({fieldName}.State);");
                sb.AppendLine("\t\t}"); //end setter

                if (propInfo.DefaultValue != "default")
                    sb.AppendLine($"\t}} = {propInfo.DefaultValue};");
                else
                    sb.AppendLine("\t}");
            }

            sb.AppendLine();
            sb.AppendLine("\tprotected override void DisposeStates()");
            sb.AppendLine("\t{");
            foreach (var propInfo in bindableProperties)
            {
                sb.AppendLine($"\t\t{propInfo.PropertySymbol.Name}.State?.RemoveByTarget(this);");
            }
            sb.AppendLine("\t}");
        }

        sb.AppendLine("}");
    }

    /// <summary>
    /// 生成Widget.Style属性
    /// </summary>
    private static string GenerateWidgetStyleProperty(string namespaceName, string className, string styleType)
    {
        return $@"
    private {styleType}? _localStyle;
    public {styleType} Style
    {{
        get
        {{
            if (_localStyle == null)
            {{
                _localStyle = new {styleType}();
                _localStyle.AddWidget(this);
            }}
            return _localStyle;
        }}
        set
        {{
            _localStyle?.RemoveWidget(this);
            _localStyle = value;
            _localStyle.AddWidget(this);
        }}
    }}

    protected override void DisposeStyle() => _localStyle?.Dispose();

";
    }

    private static void GenerateStyleObject(StringBuilder sb, string namespaceName, string className,
        ClassDeclarationSyntax classDeclaration, SemanticModel semanticModel)
    {
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("using System;");
        sb.AppendLine("using PixUI;");
        sb.Append("namespace ");
        sb.Append(namespaceName);
        sb.AppendLine(";");
        sb.AppendLine();

        sb.AppendLine($"partial class {className}");
        sb.AppendLine("{");

        var styleProperties = TypeHelper.GetBindableProperties(classDeclaration, semanticModel);
        foreach (var propInfo in styleProperties)
        {
            var returnType = propInfo.PropertySymbol.Type.ToDisplayString();
            var propertyName = propInfo.PropertySymbol.Name;
            var fieldName = propInfo.DefaultValueProxy ? $"_{propertyName}" : "field";

            if (propInfo.DefaultValueProxy)
            {
                sb.Append($"\tprivate {returnType} {fieldName}");
                if (propInfo.DefaultValueProxy) sb.Append('?');
                sb.AppendLine(";");
            }

            sb.Append($"\t{propInfo.Modifiers}");
            if (!string.IsNullOrEmpty(propInfo.Modifiers)) sb.Append(' ');
            sb.AppendLine($"partial {returnType} {propertyName}");
            sb.AppendLine("\t{");
            //getter
            sb.Append("\t\tget");
            if (propInfo.DefaultValueProxy)
            {
                sb.AppendLine();
                sb.AppendLine("\t\t{");
                sb.AppendLine($"\t\t\tif {fieldName} == null return {propInfo.DefaultValue}");
                sb.AppendLine($"\t\t\treturn {fieldName}.Value;");
                sb.AppendLine("\t\t}");
            }
            else
            {
                sb.AppendLine(";");
            }

            //setter
            sb.AppendLine("\t\tset");
            sb.AppendLine("\t\t{");
            if (!string.IsNullOrEmpty(propInfo.Validator))
            {
                sb.Append($"\t\t\tif(!(");
                sb.AppendFormat(propInfo.Validator!, "value.Value");
                sb.AppendLine("))");
                sb.AppendLine(
                    $"\t\t\t\tthrow new PropertyValueInvalidException(nameof({className}), nameof({propertyName}), \"{propInfo.Validator}\");");
            }

            if (propInfo.DefaultValueProxy)
            {
                sb.AppendLine($"\t\t\tvar changed = {fieldName} == null || {fieldName}.Value.Value != value.Value;");
                sb.AppendLine($"\t\t\tRemoveBinding({fieldName}?.State, nameof({propertyName}));");
                sb.AppendLine($"\t\t\t{fieldName} = value;");
                sb.AppendLine(
                    $"\t\t\tAddBinding({fieldName}.Value.State, nameof({propertyName}), {propInfo.Listener});");
            }
            else
            {
                sb.AppendLine($"\t\t\tvar changed = {fieldName}.Value != value.Value;");
                sb.AppendLine($"\t\t\tRemoveBinding({fieldName}.State, nameof({propertyName}));");
                sb.AppendLine($"\t\t\t{fieldName} = value;");
                sb.AppendLine($"\t\t\tAddBinding({fieldName}.State, nameof({propertyName}), {propInfo.Listener});");
            }

            sb.AppendLine($"\t\t\tif (changed) OnStyleValueChanged({propInfo.Listener});");
            sb.AppendLine("\t\t}"); //end setter

            if (!propInfo.DefaultValueProxy && propInfo.DefaultValue != "default")
                sb.AppendLine($"\t}} = {propInfo.DefaultValue};");
            else
                sb.AppendLine("\t}");
        }

        sb.AppendLine("}");
    }
}