namespace PixUI;

public enum ButtonFill
{
    /// <summary>
    /// used to fill with color for widget
    /// </summary>
    Solid,

    /// <summary>
    /// used for widget with outline border and fill color with Color.Transparent
    /// </summary>
    Outline,

    /// <summary>
    /// used for widget with fill color with Color.Transparent
    /// </summary>
    Transparent,
}